    /**
     * Si la palabra esta en el vocabulario, sin distinguir mayusculas ni
     * tildes. La palabra se compara ENTERA: partirla por los cambios de caja es
     * cosa de quien llama ({@see ErrorTextAllowlist}).
     */
    public static function contains(string $word): bool
    {
        $needle = self::fold($word);
        $low = 0;
        $high = \count(self::WORDS) - 1;

        while ($low <= $high) {
            $middle = intdiv($low + $high, 2);
            $order = strcmp(self::WORDS[$middle], $needle);

            if ($order === 0) {
                return true;
            }

            if ($order < 0) {
                $low = $middle + 1;
            } else {
                $high = $middle - 1;
            }
        }

        return false;
    }

    /**
     * Minusculas y sin tildes ni marcas combinantes: la forma en que se guarda
     * cada palabra de la lista.
     */
    public static function fold(string $word): string
    {
        $withoutMarks = preg_replace('/\p{M}+/u', '', $word) ?? '';

        return strtr(mb_strtolower($withoutMarks), self::FOLD);
    }

