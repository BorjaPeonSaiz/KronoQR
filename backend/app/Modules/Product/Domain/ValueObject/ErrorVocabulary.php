/**
 * **El vocabulario tecnico cerrado** del historico de errores (ADR-048,
 * RF-PD-15, RL-19, reglas duras 16 y 21).
 *
 * En el texto libre que se guarda en `error_events` —el mensaje, los valores de
 * texto del contexto, `app_version` y, cuando no es una ruta del producto,
 * `file`— **una palabra solo se conserva si esta aqui**. Cualquier otra pasa a
 * `…` ({@see ErrorTextAllowlist}). Es una lista de PERMITIDOS: un nombre de
 * persona no tiene forma reconocible, pero si tiene la propiedad de no ser una
 * palabra de esta lista.
 *
 * ## Que hay y de donde sale
 *
 * Minusculas, sin tildes, ordenadas byte a byte (`strcmp`), sin repetidos y con
 * al menos dos letras. La semilla salio de recorrer el repositorio:
 *
 * - las palabras de los literales de `Modules/*\/{Domain,Application}/Exception`
 *   y de las excepciones que se lanzan en cualquier punto de `app/`;
 * - los identificadores de evento del log tecnico (`product.error_history_write_failed`);
 * - las partes de los espacios de nombres y de los nombres de clase, de las
 *   rutas, de los comandos y del catalogo `ClientErrorCode`;
 * - los tipos de problema de `openapi.yaml`;
 * - los valores que mandan los clientes en su contexto (causas, motivos,
 *   ambitos, desenlaces, nombres de error);
 * - los mensajes habituales de PHP, PDO, PostgreSQL, Redis, Laravel, Symfony,
 *   V8, SpiderMonkey, JavaScriptCore, `DOMException` y Vue;
 * - los marcadores del propio saneado (`[email]`, `[iban]`, `[uuid]`…), para
 *   que sanear dos veces de lo mismo que una.
 *
 * Unos pocos llevan cifras (`utf8`, `sha256`, `base64`, `x509`…): son los
 * identificadores tecnicos que la regla de alfanumericos de
 * {@see ErrorTextAllowlist} convertiria en `[n]` si no estuvieran aqui.
 *
 * ## Dos pruebas lo vigilan, y ninguna admite excepciones
 *
 * - `ErrorVocabularyTest` exige que **no comparta ninguna palabra** con el
 *   conjunto de nombres y apellidos frecuentes de `tests/Support/Product`. Si
 *   una palabra tecnica coincide con un nombre («max», «mark», «mayor»), la
 *   palabra sale de aqui y ese mensaje la pierde.
 * - `ErrorVocabularyCoverageTest` exige que **todo lo que el producto emite**
 *   este aqui. Si falla no es una fuga: es diagnostico que se pierde.
 *
 * Una palabra nueva se anade con un PR revisado, una por linea, en su sitio
 * alfabetico. El orden no es cosmetico: {@see contains()} busca por biseccion.
 *
 * ## Dominio puro
 *
 * Una constante y dos funciones sin estado. Sin `intl`: el plegado de tildes es
 * una tabla explicita, la misma en cualquier instalacion.
 */
